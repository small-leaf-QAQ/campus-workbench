-- ============================================================
-- 校园生活工作台 · 建表脚本（给队友用）
--
-- 五张表的结构**逐列照抄**线上那套（2026-10-19 从云库 describe 出来的），
-- 所以页面代码一行都不用改就能对上。
--
-- 执行方式：在 WorkBuddy 里让它用 workbuddy_cloudservice_db_exec_sql，
--           mode 全部用 "migrate"（建表 / 改 RLS 必须走这个角色）。
--           下面每条以分号结尾的 SQL 都**单独执行一次**，共 21 条，不能整段粘贴。
--
-- 为什么要 GRANT：建表和 RLS 是**两道独立的门**。
--   只写 policy 不写 grant ⇒ 登录用户碰不到表，报 42501，看起来像策略写错了，其实是漏了授权。
--   这两道门都过了，页面才读写得到。
--
-- 幂等：建表用 if not exists；策略每张表用一个 do 块，先 drop 再 create，
--       重复跑不会报「策略已存在」。
-- ============================================================


-- ─── 语句 1 ─── 课程表
create table if not exists public.courses (
  id           bigint generated by default as identity primary key,
  owner_id     text not null default auth.uid(),
  owner_name   text,
  name         text not null,
  day          text,
  slot         text,
  exact_slot   text,
  location     text,
  teacher      text,
  weeks        text,
  created_at   timestamptz not null default now()
);

-- ─── 语句 2 ─── DDL 任务
create table if not exists public.ddl_tasks (
  id             bigint generated by default as identity primary key,
  owner_id       text not null default auth.uid(),
  owner_name     text,
  name           text not null,
  course         text,
  due_at         text,
  submit_method  text,
  priority       text,
  status         text,
  source_quote   text,
  unconfirmed    text,
  created_at     timestamptz not null default now()
);

-- ─── 语句 3 ─── 长任务拆解
create table if not exists public.plan_stages (
  id              bigint generated by default as identity primary key,
  owner_id        text not null default auth.uid(),
  owner_name      text,
  total_task      text not null,
  stage_name      text,
  deliverable     text,
  planned_start   text,
  planned_end     text,
  estimate_basis  text,
  status          text,
  created_at      timestamptz not null default now(),
  source_quote    text default ''::text,
  unconfirmed     text default ''::text
);

-- ─── 语句 4 ─── 提醒设置（每人一行）
create table if not exists public.remind_settings (
  id                  bigint generated by default as identity primary key,
  owner_id            text not null default auth.uid(),
  owner_name          text,
  remind_email        text,
  push_time           text,
  daily_digest        boolean default true,
  due_countdown       boolean default true,
  long_task_reminder  boolean default true,
  advance_days        integer default 1,
  last_push           text,
  created_at          timestamptz not null default now()
);

-- ─── 语句 5 ─── 群消息收件箱
-- status 只认「待处理 / 已处理 / 已忽略」三个值；写别的值，那一条在页面上会消失
create table if not exists public.msg_inbox (
  id          bigint generated by default as identity primary key,
  owner_id    text not null default auth.uid(),
  owner_name  text default ''::text,
  group_name  text default ''::text,
  sender      text default ''::text,
  raw_text    text default ''::text,
  msg_time    text default ''::text,
  status      text default '待处理'::text,
  route       text default ''::text,
  result_ref  text default ''::text,
  note        text default ''::text,
  created_at  timestamptz not null default now()
);


-- ─── 语句 6～10 ─── 打开五张表的 RLS（一条一张，共 5 条）
alter table public.courses         enable row level security;
alter table public.ddl_tasks       enable row level security;
alter table public.plan_stages     enable row level security;
alter table public.remind_settings enable row level security;
alter table public.msg_inbox       enable row level security;


-- ─── 语句 11～15 ─── 表授权（缺这一步，策略不生效，见文件头说明，共 5 条）
grant select, insert, update, delete on table public.courses         to authenticated, anon;
grant select, insert, update, delete on table public.ddl_tasks       to authenticated, anon;
grant select, insert, update, delete on table public.plan_stages     to authenticated, anon;
grant select, insert, update, delete on table public.remind_settings to authenticated, anon;
grant select, insert, update, delete on table public.msg_inbox       to authenticated, anon;


-- ─── 语句 16 ─── courses 的四条策略（只放行本人的行）
do $$
declare p record;
begin
  for p in select * from (values
    ('read',   'select', 'using (owner_id = auth.uid())', ''),
    ('insert', 'insert', '', 'with check (owner_id = auth.uid())'),
    ('update', 'update', 'using (owner_id = auth.uid())', 'with check (owner_id = auth.uid())'),
    ('delete', 'delete', 'using (owner_id = auth.uid())', '')
  ) as t(suffix, cmd, using_part, check_part)
  loop
    execute format('drop policy if exists %I on public.courses', 'courses_' || p.suffix || '_own');
    execute format('create policy %I on public.courses for %s to authenticated, anon %s %s',
      'courses_' || p.suffix || '_own', p.cmd, p.using_part, p.check_part);
  end loop;
end $$;

